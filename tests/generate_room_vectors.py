"""Independent Python fixtures for room identity, login, and wire crypto.

All seeds/passwords here are PUBLIC TEST DATA. Never provision these on a board.
"""
import hashlib
import hmac
from pathlib import Path
import struct
from cryptography.hazmat.primitives.asymmetric import ed25519, x25519
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def public(seed):
    return ed25519.Ed25519PrivateKey.from_private_bytes(seed).public_key().public_bytes_raw()


def shared(seed, peer):
    p = 2**255 - 19
    y = int.from_bytes(peer, "little") & ((1 << 255) - 1)
    montgomery = ((1 + y) * pow(1 - y, -1, p) % p).to_bytes(32, "little")
    return x25519.X25519PrivateKey.from_private_bytes(hashlib.sha512(seed).digest()[:32]).exchange(
        x25519.X25519PublicKey.from_public_bytes(montgomery))


def encrypt(secret, data):
    data += b"\0" * (-len(data) % 16)
    enc = Cipher(algorithms.AES(secret[:16]), modes.ECB()).encryptor()
    cipher = enc.update(data) + enc.finalize()
    return hmac.digest(secret, cipher, "sha256")[:2] + cipher


room_seed, client_seed = bytes(range(32)), bytes(range(32, 64))
room, client = public(room_seed), public(client_seed)
secret = shared(room_seed, client)
assert secret == shared(client_seed, room)
epoch = 1793500000
app = b"\x83personal"
signed = room + struct.pack("<I", epoch) + app
signature = ed25519.Ed25519PrivateKey.from_private_bytes(room_seed).sign(signed)
advert = b"\x12\x40" + signed[:36] + signature + app
nyc_scope_key = hashlib.sha256(b"#nyc").digest()[:16]
transport = int.from_bytes(hmac.digest(nyc_scope_key, b"\x04" + advert[2:], "sha256")[:2], "little")
transport = 1 if transport == 0 else 0xfffe if transport == 0xffff else transport
scoped_advert = b"\x10" + struct.pack("<HH", transport, 0) + advert[1:]
login_plain = struct.pack("<II", epoch + 1, 0) + b"test-pass-1234"
login = b"\x1d\x40" + room[:1] + client + encrypt(secret, login_plain)
# Pinned upstream src/helpers/TxtDataHelpers.h: SIGNED_PLAIN=2, CLI_DATA=1.
# Keep the independent wire value here; do not import the implementation constant.
push_plain = struct.pack("<I", epoch + 4) + b"\x08" + room[:4] + b"personal is online"
push = b"\x0a\x40" + client[:1] + room[:1] + encrypt(secret, push_plain)
second_seed = bytes(range(64, 96))
second_client = public(second_seed)
second_login = b"\x1d\x40" + room[:1] + second_client + encrypt(
    shared(second_seed, room), struct.pack("<II", epoch + 20, 0) + b"test-pass-1234")
vectors = {
    "ROOM_SEED": room_seed, "ROOM_PUBLIC": room, "CLIENT_SEED": client_seed,
    "CLIENT_PUBLIC": client, "SHARED_SECRET": secret, "ROOM_ADVERT": advert,
    "ROOM_SCOPE_NYC_KEY": nyc_scope_key, "ROOM_ADVERT_NYC": scoped_advert,
    "ROOM_LOGIN": login,
    "ROOM_HISTORY_PUSH": push,
    "ROOM_HISTORY_ACK": hashlib.sha256(push_plain + client).digest()[:4],
    "SECOND_CLIENT_SEED": second_seed,
    "SECOND_CLIENT_LOGIN": second_login,
    "ROOM_WRONG_PASSWORD": b"\x1d\x40" + room[:1] + client + encrypt(secret, struct.pack("<II", epoch + 1, 0) + b"wrong-password-123"),
}
# Two distinct local identities deliberately share a routing prefix.
for i in range(10000):
    seed = hashlib.sha256(f"room collision {i}".encode()).digest()
    if public(seed)[0] == room[0] and public(seed) != room:
        vectors["COLLIDING_ROOM_SEED"] = seed
        break
else:
    raise RuntimeError("No collision fixture")
# Outbound client vectors use the same public test identities, independently of C++ codecs.
client_app = b"\x81Automation"
client_signed = client + struct.pack("<I", epoch) + client_app
client_signature = ed25519.Ed25519PrivateKey.from_private_bytes(client_seed).sign(client_signed)
client_plain = struct.pack("<I", epoch + 1) + b"\0Hello peer"
client_ack = hashlib.sha256(client_plain + client).digest()[:4]
vectors.update({
    "CLIENT_ADVERT": b"\x12\x40" + client_signed[:36] + client_signature + client_app,
    "CLIENT_DM": b"\x09\x40" + room[:1] + client[:1] + encrypt(secret, client_plain),
    "CLIENT_DM_ACK": client_ack,
    "CLIENT_EMPTY_PATH_ACK": b"\x21\x40" + client[:1] + room[:1] + encrypt(secret, b"\x40\x03" + client_ack),
    "CLIENT_PATH_ACK": b"\x21\x40" + client[:1] + room[:1] + encrypt(
        secret, b"\x41\x12\x34\x03" + client_ack + b"\0\x42"),
})
header = "// PUBLIC synthetic test seeds, generated by generate_room_vectors.py.\n#pragma once\n"
for name, value in vectors.items():
    header += f'inline constexpr const char *{name} = "{value.hex()}";\n'
Path(__file__).with_name("room_vectors.h").write_text(header)
