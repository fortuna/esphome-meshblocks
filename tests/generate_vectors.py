"""Independent Python wire oracle for the pinned MeshCore channel-text subset.

Uses Python hashlib/hmac and cryptography AES, not the C++ codec under test.
These are deterministic synthetic vectors, not captured stock-firmware traffic.
"""
import hashlib
import hmac
from pathlib import Path
import struct

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes


def frame(key, timestamp, text, flags=0):
    plain = struct.pack("<IB", timestamp, flags) + text
    plain += b"\0" * (-len(plain) % 16)
    encryptor = Cipher(algorithms.AES(key[:16]), modes.ECB()).encryptor()
    cipher = encryptor.update(plain) + encryptor.finalize()
    mac = hmac.digest(key.ljust(32, b"\0"), cipher, "sha256")[:2]
    return bytes([0x15, 0x40, hashlib.sha256(key).digest()[0]]) + mac + cipher


def scoped_frame(original, scope_key):
    # Transport HMAC includes payload type and the complete encrypted payload;
    # it excludes route header, transport codes, and path. Stock emits LE codes.
    digest = hmac.digest(scope_key, bytes([5]) + original[2:], "sha256")
    code = int.from_bytes(digest[:2], "little")
    code = 1 if code == 0 else 0xfffe if code == 0xffff else code
    return bytes([0x14]) + struct.pack("<HH", code, 0) + original[1:]


testing = hashlib.sha256(b"#testing").digest()[:16]
public = bytes.fromhex("8b3387e9c5cdea6ac9e5edbaa115cd72")
key32 = bytes(range(1, 33))
vectors = {
    "TESTING_KEY": testing.hex(),
    "TESTING_FRAME": frame(testing, 1793491200, b"Peer: probe-peer-001").hex(),
    "PUBLIC_FRAME": frame(public, 1793491201, b"Public peer: hello").hex(),
    "KEY32_FRAME": frame(key32, 1793491202, b"Peer: key32").hex(),
    "ALIGNED_FRAME": frame(testing, 1793491203, b"P: 12345678").hex(),  # 16-byte plaintext; no extra block
    "MAX_FRAME": frame(testing, 1793491204, b"P: " + b"x" * 157).hex(),
    "UNSUPPORTED_TEXT_FRAME": frame(testing, 1793491205, b"P: unsupported", flags=4).hex(),
    "UTF8_FRAME": frame(testing, 1793491206, "Peer: caf\u00e9".encode()).hex(),
}
original = bytes.fromhex(vectors["TESTING_FRAME"])
nyc = hashlib.sha256(b"#nyc").digest()[:16]
vectors["NYC_SCOPE_KEY"] = nyc.hex()
vectors["NYC_SCOPED_FRAME"] = scoped_frame(original, nyc).hex()
vectors["NYC_SCOPED_MAX_FRAME"] = scoped_frame(bytes.fromhex(vectors["MAX_FRAME"]), nyc).hex()
# Real HMAC fixtures for the two reserved-code remappings, not a mocked digest.
remaining = {0: "ZERO", 0xffff: "FFFF"}
for index in range(1000000):
    scope_key = hashlib.sha256(f"#edge{index}".encode()).digest()[:16]
    code = int.from_bytes(hmac.digest(scope_key, bytes([5]) + original[2:], "sha256")[:2], "little")
    if code in remaining:
        name = remaining.pop(code)
        vectors[f"{name}_SCOPE_KEY"] = scope_key.hex()
        vectors[f"{name}_SCOPED_FRAME"] = scoped_frame(original, scope_key).hex()
    if not remaining:
        break
else:
    raise RuntimeError("Could not construct reserved transport-code fixtures")
# A real 1-byte channel-hash collision: both candidates must be tried.
target = hashlib.sha256(testing).digest()[0]
for index in range(10000):
    candidate = hashlib.sha256(f"#collision{index}".encode()).digest()[:16]
    if hashlib.sha256(candidate).digest()[0] == target and candidate != testing:
        vectors["COLLIDING_KEY"] = candidate.hex()
        break
else:
    raise RuntimeError("Could not construct collision fixture")

header = "// Generated by tests/generate_vectors.py; deterministic independent oracle.\n#pragma once\n"
for name, value in vectors.items():
    header += f'inline constexpr const char *{name} = "{value}";\n'
Path(__file__).with_name("wire_vectors.h").write_text(header)
